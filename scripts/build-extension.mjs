// Builds the unpacked extension into extension/dist.
//   node scripts/build-extension.mjs          production (web origin from SCENELINGO_WEB_ORIGIN or https://<project>.web.app)
//   node scripts/build-extension.mjs --dev    also allows http://localhost:5173 for the web app
//   add --out <dir> to build somewhere other than extension/dist
// Reads Firebase web config (public identifiers) from .env.local. Never reads or copies secrets.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const ext = path.join(root, "extension");
const outIdx = process.argv.indexOf("--out");
const dist = outIdx > 0 ? path.resolve(process.argv[outIdx + 1]) : path.join(ext, "dist"); // --out <dir> builds elsewhere, leaving extension/dist alone
const dev = process.argv.includes("--dev");

function readEnv(file) {
  if (!fs.existsSync(file)) return {};
  return Object.fromEntries(
    fs.readFileSync(file, "utf8").split("\n")
      .filter((l) => l.trim() && !l.trim().startsWith("#") && l.includes("="))
      .map((l) => { const i = l.indexOf("="); return [l.slice(0, i).trim(), l.slice(i + 1).trim().replace(/^["']|["']$/g, "")]; })
  );
}
const env = { ...readEnv(path.join(root, ".env.local")), ...process.env };
const need = (k) => { if (!env[k]) { console.error(`Missing ${k} (set it in .env.local)`); process.exit(1); } return env[k]; };

const projectId = need("VITE_FIREBASE_PROJECT_ID");
const apiKey = need("VITE_FIREBASE_API_KEY");
const webOrigin = (env.SCENELINGO_WEB_ORIGIN || `https://${projectId}.web.app`).replace(/\/$/, "");
const devOrigin = "http://localhost:5173";
const allowedOrigins = dev ? [webOrigin, devOrigin] : [webOrigin];

// Dev-only: point the extension at a mock Firestore/token server for automated tests.
const mockBase = dev ? (env.SCENELINGO_MOCK_BASE || "") : "";
const endpoints = mockBase ? { firestore: mockBase, secureToken: mockBase } : {};

const keyFile = path.join(ext, "key", "public.b64"); // the PUBLIC key: committed, so every build gets the same extension ID
if (!fs.existsSync(keyFile)) { console.error("Missing extension/key/public.b64 (the public key that fixes the extension ID)"); process.exit(1); }

fs.rmSync(dist, { recursive: true, force: true });
fs.cpSync(path.join(ext, "src"), dist, { recursive: true });

const toMatch = (o) => (o.startsWith("http://localhost") ? "http://localhost/*" : `${o}/*`);
const manifest = JSON.parse(fs.readFileSync(path.join(ext, "manifest.template.json"), "utf8"));
manifest.key = fs.readFileSync(keyFile, "utf8").trim();
manifest.host_permissions = [
  "https://www.youtube.com/*",
  "https://www.netflix.com/*",
  "https://firestore.googleapis.com/*",
  "https://securetoken.googleapis.com/*",
  ...allowedOrigins.map(toMatch),
  ...(mockBase ? [`${mockBase}/*`] : []),
];
manifest.externally_connectable.matches = allowedOrigins.map(toMatch);
if (dev) manifest.name += " (dev)";
// Test-only: omit the automatic content script so a tab has none, like a tab opened before install.
if (dev && env.SCENELINGO_TEST_NO_CONTENT_SCRIPT === "1") delete manifest.content_scripts;
fs.writeFileSync(path.join(dist, "manifest.json"), JSON.stringify(manifest, null, 2) + "\n");

fs.writeFileSync(
  path.join(dist, "config.js"),
  `// Generated by scripts/build-extension.mjs. Public Firebase identifiers only.\n` +
  `export const CONFIG = ${JSON.stringify({ firebase: { projectId, apiKey }, webOrigin, allowedOrigins, endpoints }, null, 2)};\n`
);
console.log(`Built ${dev ? "DEV" : "production"} extension -> ${path.relative(root, dist)}`);
console.log(`  web app origin : ${allowedOrigins.join(", ")}`);
console.log(`  extension id   : ${fs.readFileSync(path.join(ext, "key", "extension-id.txt"), "utf8").trim()}`);
